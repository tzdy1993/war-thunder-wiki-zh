ANCHOR = "    'Fighters': '战斗机',"


def main() -> int:
    src = CORE.read_text(encoding="utf-8")
    if ANCHOR not in src:
        print("anchor not found")
        return 1
    existing = src[src.index("const FIXED_TRANSLATIONS") : src.index("// BEGIN GENERATED UNIT")]
    keys = set(__import__("re").findall(r"^  '([^']+)':", existing, __import__("re").M))
    new_lines = []
    dup = 0
    for en, cn in ENTRIES:
        if en in keys:
            dup += 1
            continue
        new_lines.append(f"    {en!r}: {cn!r},")
        keys.add(en)
    if not new_lines:
        print(f"no new entries (duplicates: {dup})")
        return 0
    block = "\n".join(new_lines) + "\n"
    src = src.replace(ANCHOR, block + ANCHOR)
    CORE.write_text(src, encoding="utf-8", newline="\n")
    print(f"inserted {len(new_lines)} entries (skipped {dup} duplicates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
